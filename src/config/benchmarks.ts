export const BENCHMARK_BY_ID: Readonly<Record<string, BenchmarkMeta>> = Object.fromEntries(
  BENCHMARKS.map((b) => [b.id, b]),
);

export function getActiveBenchmarks(domainId: DomainId): readonly BenchmarkMeta[] {
  return BENCHMARKS.filter(
    (b) =>
      b.domainId === domainId &&
      (b.lifecycleState === "ACTIVE" || b.lifecycleState === "WATCHLIST"),
  );
}

export function getActiveBenchmarksForRegime(
  domainId: DomainId,
  regime: HarnessRegime,
): readonly BenchmarkMeta[] {
  return getActiveBenchmarks(domainId).filter((b) => b.regimes.includes(regime));
}

export function getCandidateBenchmarks(domainId: DomainId): readonly BenchmarkMeta[] {
  return BENCHMARKS.filter((b) => b.domainId === domainId && b.lifecycleState === "CANDIDATE");
}
