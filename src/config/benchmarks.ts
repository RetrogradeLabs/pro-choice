export function getRegimesForDomain(domainId: DomainId): readonly HarnessRegime[] {
  if (domainId === "coding") return ["standardized"];
  return ["native"];
}

export function getCoverageFloorForDomain(
  domainId: DomainId,
  activeBenchmarkCount: number,
): number {
  const configured = DOMAIN_BY_ID[domainId].coverageFloor;
  return Math.max(1, Math.min(activeBenchmarkCount, configured));
}

export function getAnchorMinCoverageForDomain(
  domainId: DomainId,
  activeBenchmarkCount: number,
): number {
  const configured = DOMAIN_BY_ID[domainId].anchorMinCoverage;
  return Math.max(1, Math.min(activeBenchmarkCount, configured));
}

